import type { Block } from './symbols';

// The block format: rows from the top down; the last string is row 1, just above the (implicit) ground.
// Shorter rows are padded with '.'. The symbols: track/symbols.ts.
// Reach at the PLAYER constants (runSpeed 145, about 9 tiles/s, jump -320, gravity 900, glide cap 40):
//   running on ground or a platform collects rows +1 and +2 above it (so ground feathers start at row 3)
//   a full jump collects up to row +5, apex ~3 cols after takeoff, lands ~6.5 cols after
//   a double jump near the apex collects up to row +8
//   platforms: at most 3 rows above where you jump from (a 3-row step has ~9 px to spare)
//   gliding sinks about 1 row per 3.5 cols
// `npm run check:blocks` simulates every block.
